import Fastify from 'fastify';
import cookie from '@fastify/cookie';
import cors from '@fastify/cors';
import multipart from '@fastify/multipart';
import type { Kysely } from 'kysely';
import type PgBoss from 'pg-boss';
import { serializerCompiler, validatorCompiler, type ZodTypeProvider } from 'fastify-type-provider-zod';
import type { Database } from '@kt/db';
import type { Config } from './config.js';
import errorsPlugin from './plugins/errors.js';
import dbPlugin from './plugins/db.js';
import authPlugin from './plugins/auth.js';
import authRoutes from './modules/auth/routes.js';
import userRoutes from './modules/core/users.js';
import roleRoutes from './modules/core/roles.js';
import tenantRoutes from './modules/core/tenants.js';
import fiscalYearRoutes from './modules/core/fiscalYears.js';
import settingRoutes from './modules/core/settings.js';
import prefRoutes from './modules/core/prefs.js';
import coaRoutes from './modules/coa/routes.js';
import masterRoutes from './modules/master/routes.js';
import itemRoutes from './modules/inventory/items.routes.js';
import priceListRoutes from './modules/inventory/priceLists.routes.js';
import stockVoucherRoutes from './modules/inventory/stockVouchers.js';
import assemblyRoutes from './modules/inventory/assembly.js';
import stocktakeRoutes from './modules/inventory/stocktake.js';
import stockReportRoutes from './modules/inventory/reports.js';
import tradeReportRoutes from './modules/inventory/tradeReports.js';
import stockMoveRoutes from './modules/inventory/stockMoves.js';
import costingRunRoutes from './modules/inventory/costingRun.js';
import landedCostRoutes from './modules/inventory/landedCost.js';
import auditRoutes from './modules/audit/routes.js';
import numberingRoutes from './modules/ledger/numbering.js';
import voucherRoutes from './modules/ledger/vouchers.routes.js';
import periodRoutes from './modules/ledger/periods.routes.js';
import attachmentRoutes from './modules/ledger/attachments.js';
import openingBalanceRoutes from './modules/ledger/openingBalance.js';
import openingStockRoutes from './modules/inventory/openingStock.js';
import balanceRoutes from './modules/ledger/balances.js';
import closingRoutes from './modules/ledger/closing.js';
import periodCloseRoutes from './modules/ledger/periodClose.routes.js';
import reportingRoutes from './modules/reporting/routes.js';
import cashRoutes from './modules/cash/routes.js';
import toolsRoutes from './modules/tools/routes.js';
import arapRoutes from './modules/arap/routes.js';
import taxRoutes from './modules/tax/routes.js';
import invoiceRoutes from './modules/invoices/routes.js';
import orderRoutes from './modules/orders/routes.js';
import assetRoutes from './modules/assets/routes.js';
import loanRoutes from './modules/loans/routes.js';
import einvoiceRoutes from './modules/einvoice/routes.js';
import openingAssetRoutes from './modules/assets/openingAssets.js';

declare module 'fastify' { interface FastifyInstance { config: Config; boss: PgBoss | null } }

export async function buildApp(opts: { db: Kysely<Database>; config: Config; boss?: PgBoss }) {
  // cast: các overload http/http2 của Fastify không chấp nhận hợp boolean|number|string, giá trị thật vẫn giữ nguyên
  const app = Fastify({ logger: process.env.NODE_ENV !== 'test', trustProxy: opts.config.TRUST_PROXY as boolean }).withTypeProvider<ZodTypeProvider>();
  app.setValidatorCompiler(validatorCompiler);
  app.setSerializerCompiler(serializerCompiler);
  app.decorate('config', opts.config);
  app.decorate('boss', opts.boss ?? null);
  await app.register(errorsPlugin);
  await app.register(cors, { origin: opts.config.WEB_ORIGIN, credentials: true });
  await app.register(cookie, { secret: opts.config.SESSION_SECRET });
  await app.register(multipart, { limits: { fileSize: 20 * 1024 * 1024 } });
  await app.register(dbPlugin, { db: opts.db });
  await app.register(authPlugin);
  await app.register(authRoutes);
  await app.register(userRoutes);
  await app.register(roleRoutes);
  await app.register(tenantRoutes);
  await app.register(fiscalYearRoutes);
  await app.register(settingRoutes);
  await app.register(prefRoutes);
  await app.register(coaRoutes);
  await app.register(masterRoutes);
  await app.register(itemRoutes);
  await app.register(priceListRoutes);
  await app.register(stockVoucherRoutes);
  await app.register(assemblyRoutes);
  await app.register(stocktakeRoutes);
  await app.register(stockReportRoutes);
  await app.register(tradeReportRoutes);
  await app.register(stockMoveRoutes);
  await app.register(costingRunRoutes);
  await app.register(landedCostRoutes);
  await app.register(auditRoutes);
  await app.register(numberingRoutes);
  await app.register(voucherRoutes);
  await app.register(periodRoutes);
  await app.register(attachmentRoutes);
  await app.register(openingBalanceRoutes);
  await app.register(openingStockRoutes);
  await app.register(balanceRoutes);
  await app.register(closingRoutes);
  await app.register(periodCloseRoutes);
  await app.register(reportingRoutes);
  await app.register(cashRoutes);
  await app.register(toolsRoutes);
  await app.register(arapRoutes);
  await app.register(taxRoutes);
  await app.register(invoiceRoutes);
  await app.register(orderRoutes);
  await app.register(assetRoutes);
  await app.register(loanRoutes);
  await app.register(einvoiceRoutes);
  await app.register(openingAssetRoutes);
  app.get('/api/health', async () => ({ ok: true }));
  return app;
}
